const mongoose = require('mongoose');

/** Common options: every record belongs to a user and carries a client-generated stable id. */
const baseFields = {
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  clientId: { type: String, required: true, trim: true }, // UUID generated by the Flutter app (localId)
};

const schemaOptions = {
  timestamps: true,
  toJSON: {
    transform: (_doc, ret) => {
      ret.id = String(ret._id);
      delete ret._id;
      delete ret.__v;
      delete ret.userId;
      return ret;
    },
  },
};

module.exports = { baseFields, schemaOptions };
